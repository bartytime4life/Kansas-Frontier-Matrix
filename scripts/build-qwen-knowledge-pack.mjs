/**
 * Generates scripts/qwen-knowledge-pack.mjs from the Site's own source
 * registries plus the curated vocabulary in qwen-knowledge-curated.mjs.
 *
 *   node scripts/build-qwen-knowledge-pack.mjs          # write the pack
 *   node scripts/build-qwen-knowledge-pack.mjs --check  # exit 1 when stale
 *
 * The output is deterministic (no timestamps) so a test can prove the
 * committed pack still matches the registries the map actually renders.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";
import {
  QWEN_KNOWLEDGE_DOMAIN_IDEAS,
  QWEN_KNOWLEDGE_GLOSSARY,
  QWEN_KNOWLEDGE_PRINCIPLES,
  QWEN_KNOWLEDGE_PROJECT_IDEAS,
} from "./qwen-knowledge-curated.mjs";

const sourceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const QWEN_KNOWLEDGE_PACK_PATH = path.join(sourceRoot, "scripts", "qwen-knowledge-pack.mjs");
export const QWEN_KNOWLEDGE_PACK_VERSION = "kfm-qwen-knowledge-v1";

const modules = new Map();
async function moduleUrl(file) {
  const resolved = path.resolve(file);
  if (modules.has(resolved)) return modules.get(resolved);
  let javascript = ts.transpileModule(await readFile(resolved, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  for (const match of [...javascript.matchAll(/from ["'](\.[^"']+)["']/g)]) {
    javascript = javascript.replace(
      match[0],
      `from ${JSON.stringify(await moduleUrl(path.resolve(path.dirname(resolved), match[1]) + ".ts"))}`,
    );
  }
  const url = `data:text/javascript;base64,${Buffer.from(javascript).toString("base64")}`;
  modules.set(resolved, url);
  return url;
}

export async function buildQwenKnowledgePack() {
  const { OFFICIAL_CONTEXT_SOURCES } = await import(await moduleUrl(path.join(sourceRoot, "app", "live-context.ts")));
  const { EXTERNAL_CONTEXT_SOURCES } = await import(await moduleUrl(path.join(sourceRoot, "app", "external-context-sources.ts")));
  const domains = [...new Set(OFFICIAL_CONTEXT_SOURCES.map((source) => source.domain))];
  const unknownIdeaDomains = Object.keys(QWEN_KNOWLEDGE_DOMAIN_IDEAS).filter((domain) => !domains.includes(domain));
  if (unknownIdeaDomains.length) throw new Error(`Curated ideas name unknown domains: ${unknownIdeaDomains.join(", ")}`);
  return {
    version: QWEN_KNOWLEDGE_PACK_VERSION,
    generatedBy: "scripts/build-qwen-knowledge-pack.mjs",
    derivedFrom: [
      "app/live-context.ts#OFFICIAL_CONTEXT_SOURCES",
      "app/external-context-sources.ts#EXTERNAL_CONTEXT_SOURCES",
      "scripts/qwen-knowledge-curated.mjs",
    ],
    principles: QWEN_KNOWLEDGE_PRINCIPLES,
    glossary: QWEN_KNOWLEDGE_GLOSSARY,
    domains: domains.map((domain) => ({
      name: domain,
      sourceIds: OFFICIAL_CONTEXT_SOURCES.filter((source) => source.domain === domain).map((source) => source.id),
      ideas: QWEN_KNOWLEDGE_DOMAIN_IDEAS[domain] ?? [],
    })),
    projectIdeas: QWEN_KNOWLEDGE_PROJECT_IDEAS,
    officialSources: OFFICIAL_CONTEXT_SOURCES.map((source) => ({
      id: source.id,
      title: source.title,
      shortTitle: source.shortTitle,
      organization: source.organization,
      domain: source.domain,
      kind: source.kind,
      cadence: source.cadence,
      freshness: source.freshness,
      boundary: source.boundary,
      fallback: source.fallback,
      attribution: source.attribution,
      sourceUrl: source.sourceUrl,
      evidenceRole: source.evidenceRole,
    })),
    displaySources: EXTERNAL_CONTEXT_SOURCES.map((source) => ({
      id: source.id,
      title: source.title,
      organization: source.organization,
      kind: source.kind,
      boundary: source.boundary,
      fallback: source.fallback,
      evidenceRole: source.evidenceRole,
    })),
  };
}

export async function renderQwenKnowledgePack() {
  const pack = await buildQwenKnowledgePack();
  return [
    "// GENERATED by scripts/build-qwen-knowledge-pack.mjs. Do not edit by hand.",
    "// Regenerate after changing source registries or qwen-knowledge-curated.mjs.",
    "const deepFreeze = (value) => {",
    "  if (value && typeof value === \"object\") {",
    "    for (const item of Object.values(value)) deepFreeze(item);",
    "    Object.freeze(value);",
    "  }",
    "  return value;",
    "};",
    "",
    `export const QWEN_KNOWLEDGE_PACK = deepFreeze(${JSON.stringify(pack, null, 2)});`,
    "",
  ].join("\n");
}

const invokedDirectly = process.argv[1]
  && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;
if (invokedDirectly) {
  const rendered = await renderQwenKnowledgePack();
  if (process.argv.includes("--check")) {
    const current = await readFile(QWEN_KNOWLEDGE_PACK_PATH, "utf8").catch(() => "");
    if (current !== rendered) {
      process.stderr.write("qwen-knowledge-pack.mjs is stale. Run: node scripts/build-qwen-knowledge-pack.mjs\n");
      process.exit(1);
    }
    process.stdout.write("qwen-knowledge-pack.mjs is current.\n");
  } else {
    await writeFile(QWEN_KNOWLEDGE_PACK_PATH, rendered);
    process.stdout.write(`Wrote ${path.relative(sourceRoot, QWEN_KNOWLEDGE_PACK_PATH)} (${Buffer.byteLength(rendered)} bytes).\n`);
  }
}
