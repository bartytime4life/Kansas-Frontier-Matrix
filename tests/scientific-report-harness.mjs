import {readFile} from 'node:fs/promises';
import ts from 'typescript';
import {terrainModules} from './terrain-preparation-harness.mjs';
const url = code => `data:text/javascript;base64,${Buffer.from(code).toString('base64')}`;
const compile = async name => ts.transpileModule(await readFile(new URL(`../app/${name}.ts`, import.meta.url), 'utf8'), {compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const materials = url(await compile('subsurface-materials'));
const subsurface = url((await compile('subsurface-model')).replace('"./subsurface-materials"',JSON.stringify(materials)));
const outline = url(await compile('kansas-orientation'));
const awaitedOutline=await import(outline),awaitedSubsurface=await import(subsurface);
export const scientific = {};
new Function('exports','require',ts.transpileModule(await readFile(new URL('../app/scientific-report.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText)(scientific,n=>n==='./terrain-report'?terrainModules['terrain-report']:n==='./kansas-orientation'?awaitedOutline:awaitedSubsurface);
