import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm, symlink } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { applicationIdentity, verifyHostedIdentity } from '../scripts/build-identity.mjs';

test('the normal hot-reload command creates identity before Vite on a fresh source tree', async t => {
  const root = await fixture(t);
  const pkg = JSON.parse(await readFile('package.json', 'utf8'));
  const command = pkg.scripts['dev:local'] ? 'dev:local' : 'dev';
  await writeFile(join(root, 'package.json'), JSON.stringify({ type: 'module', scripts: pkg.scripts }));
  await mkdir(join(root, 'scripts'));
  await writeFile(join(root, 'scripts/build-identity.mjs'), await readFile('scripts/build-identity.mjs'));
  // Asset preparation is independent of the prerequisite being exercised here.
  for (const name of ['prepare-maplibre-assets.mjs', 'prepare-lightning-reader.mjs']) {
    await writeFile(join(root, 'scripts', name), '');
  }
  await mkdir(join(root, 'node_modules/.bin'), { recursive: true });
  await writeFile(join(root, 'node_modules/.bin/vite'), `#!/usr/bin/env node
const fs = require('node:fs');
const assert = require('node:assert/strict');
const identity = JSON.parse(fs.readFileSync('app/build-info.generated.json', 'utf8'));
assert.match(identity.sourceDigest, /^sha256:[a-f0-9]{64}$/);
assert.ok(identity.sourceFileCount > 0);
console.log('STARTED_WITH_IDENTITY');
`, { mode: 0o755 });
  const output = execFileSync('npm', ['run', command, '--', '--help'], {
    cwd: root, encoding: 'utf8', timeout: 20000, stdio: ['ignore', 'pipe', 'pipe'],
  });
  assert.match(output, /STARTED_WITH_IDENTITY/);
});

async function fixture(t) {
  const root = await mkdtemp(join(tmpdir(), 'kfm-build-identity-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  for (const name of ['package.json', 'package-lock.json', 'godaddy-source.json', 'next.config.ts', 'vite.config.ts', 'tsconfig.json', 'postcss.config.mjs']) await writeFile(join(root, name), '{}');
  for (const name of ['app', 'server', 'public']) await mkdir(join(root, name));
  await writeFile(join(root, 'app/page.tsx'), 'map');
  return root;
}

test('application changes alter identity while generated bytes, secrets and stores are excluded', async t => {
  const root = await fixture(t);
  const before = await applicationIdentity(root);
  assert.equal(before.commitState, 'GIT_UNAVAILABLE'); assert.equal(before.sourceCommit, null);
  await writeFile(join(root, '.env'), 'PRIVATE_SECRET=never-read');
  await mkdir(join(root, '.sites-runtime')); await writeFile(join(root, '.sites-runtime/store'), 'private');
  await mkdir(join(root, 'public/assets')); await writeFile(join(root, 'public/assets/client.js'), 'generated');
  await writeFile(join(root, 'app/build-info.generated.json'), '{}');
  assert.equal((await applicationIdentity(root)).sourceDigest, before.sourceDigest);
  await writeFile(join(root, 'app/page.tsx'), 'changed map');
  const changed = await applicationIdentity(root);
  assert.notEqual(changed.sourceDigest, before.sourceDigest);
  assert.equal((await applicationIdentity(root)).sourceDigest, changed.sourceDigest);
  await writeFile(join(root, 'package-lock.json'), '{"dependency":"changed"}');
  assert.notEqual((await applicationIdentity(root)).sourceDigest, changed.sourceDigest);
});

test('symlinked application input is held rather than following an external file', async t => {
  const root = await fixture(t);
  await symlink(join(root, 'package.json'), join(root, 'app/external.json'));
  await assert.rejects(applicationIdentity(root), /SOURCE_SYMLINK_HELD/);
});

test('a dirty checkout cannot advertise its parent commit as the source of its changed bytes', async t => {
  const root = await fixture(t);
  const git = args => execFileSync('git', args, { cwd: root, stdio: 'ignore' });
  git(['init']); git(['add', '.']); git(['-c', 'user.name=KFM Test', '-c', 'user.email=test@example.invalid', 'commit', '-m', 'fixture']);
  const clean = await applicationIdentity(root);
  assert.match(clean.sourceCommit, /^[a-f0-9]{40}$/); assert.equal(clean.commitState, 'CLEAN_CHECKOUT');
  await writeFile(join(root, 'server/runtime.mjs'), 'changed runtime');
  const dirty = await applicationIdentity(root);
  assert.equal(dirty.sourceCommit, null); assert.equal(dirty.commitState, 'WORKTREE_MODIFIED');
  assert.notEqual(dirty.sourceDigest, clean.sourceDigest);
});

test('hosted comparison requires actual matching application bytes and validates the response', async t => {
  const expected = await applicationIdentity(await fixture(t));
  const fetcher = value => async (url, options) => {
    assert.equal(url.pathname, '/api/build'); assert.equal(options.redirect, 'error'); assert.equal(options.cache, 'no-store');
    return Response.json(value);
  };
  assert.equal((await verifyHostedIdentity(expected, 'https://kansasfrontiermatrix.com', fetcher(expected))).outcome, 'APPLICATION_INPUTS_MATCH');
  assert.equal((await verifyHostedIdentity(expected, 'https://kansasfrontiermatrix.com', fetcher({...expected, sourceDigest:'sha256:'+'0'.repeat(64)}))).outcome, 'APPLICATION_INPUTS_DIFFER');
  await assert.rejects(verifyHostedIdentity(expected, 'https://kansasfrontiermatrix.com', async () => new Response('blocked', {status:403})), /HOSTED_IDENTITY_UNAVAILABLE/);
  await assert.rejects(verifyHostedIdentity(expected, 'https://kansasfrontiermatrix.com', fetcher({profile:expected.profile})), /HOSTED_IDENTITY_INVALID/);
  await assert.rejects(verifyHostedIdentity(expected, 'https://kansasfrontiermatrix.com', async () => new Response('x'.repeat(4097), {headers:{'content-type':'application/json'}})), /HOSTED_IDENTITY_INVALID/);
  await assert.rejects(verifyHostedIdentity(expected, 'https://user:secret@example.test'), /INVALID_VERIFICATION_ORIGIN/);
  await assert.rejects(verifyHostedIdentity(expected, 'http://example.test'), /INVALID_VERIFICATION_ORIGIN/);
});
